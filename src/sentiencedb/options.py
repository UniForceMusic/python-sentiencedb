"""Connection options and the debug callback type.

PHP keys its dialect options by dialect class; since a connection only ever has one active dialect,
sentiencedb uses a single flat mapping that both the adapter and the dialect read from.
"""

from __future__ import annotations

from collections.abc import Callable, Mapping
from typing import TypedDict

DebugCallback = Callable[[str, float, str | None], None]
"""``debug(query, start, error)`` -- called after every statement, successful or not.

``query`` is the SQL with parameters interpolated, ``start`` is the ``time.time()`` at which the statement
started and ``error`` is the driver's error message, or ``None`` on success.
"""


class Options(TypedDict, total=False):
    """Options accepted by :meth:`sentiencedb.Database.connect`. Every key is optional."""

    # -- threading (all adapters) -------------------------------------------------------------------
    max_connections: int
    """Cap on concurrently open connections (one per thread). Unlimited when absent."""
    acquire_timeout: float
    """Seconds a thread waits for a free slot before :class:`~sentiencedb.exceptions.ConnectionLimitError`.
    Waits forever when absent."""

    # -- MySQL / MariaDB adapter --------------------------------------------------------------------
    charset: str
    """``SET NAMES <charset>`` after connecting."""
    collation: str
    """``SET NAMES <charset> COLLATE <collation>`` (requires ``charset``)."""
    engine: str
    """``SET SESSION default_storage_engine = <engine>`` after connecting."""

    # -- PostgreSQL adapter -------------------------------------------------------------------------
    ssl_mode: str
    ssl_cert: str
    ssl_key: str
    ssl_root_cert: str
    ssl_crl: str
    client_encoding: str
    search_path: str
    """``SET search_path TO <search_path>`` after connecting."""

    # -- SQLite adapter -----------------------------------------------------------------------------
    read_only: bool
    encryption_key: str
    """``PRAGMA key`` (only meaningful with SQLCipher builds)."""
    busy_timeout: int
    """Milliseconds to wait on a locked database."""
    encoding: str
    journal_mode: str
    foreign_keys: bool
    """``PRAGMA foreign_keys = ON`` when true."""
    deprecated_case_sensitive_like: bool
    """``PRAGMA case_sensitive_like = ON`` when true."""
    create_functions: Mapping[str, Callable[..., object]]
    """User defined SQL functions registered on every connection; may override ``REGEXP`` and ``regexp_like``."""
    optimize: bool
    """Run ``PRAGMA optimize`` before a connection is closed."""

    # -- dialects -----------------------------------------------------------------------------------
    use_regexp: bool
    """MySQL >= 8 / SQLite: use the ``REGEXP`` operator instead of ``regexp_like()``."""
    use_tilde_regex: bool
    """PostgreSQL >= 15: use the ``~`` operator instead of ``regexp_like()``."""
    use_serials: bool
    """PostgreSQL: emit ``SERIAL``/``BIGSERIAL`` instead of ``GENERATED BY DEFAULT AS IDENTITY``."""
    strict: bool
    """SQLite: append ``STRICT`` to ``CREATE TABLE``."""


__all__ = ["DebugCallback", "Options"]
